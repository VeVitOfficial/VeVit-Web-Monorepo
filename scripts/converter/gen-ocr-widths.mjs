#!/usr/bin/env node
// Advance widths (1/1000 em) of the regular faces the converter ships, for OCR font fitting
// (src/lib/converter/pdf/ocr-widths.ts). Reads TTFs (cmap format 4 + hmtx), no dependencies.
//   node scripts/converter/gen-ocr-widths.mjs [fontDir]   (default tests/converter/fonts)
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const dir = process.argv[2] ?? path.join(root, "tests/converter/fonts");
const FACES = { "Liberation Serif": "LiberationSerif-Regular.ttf", Caladea: "Caladea-Regular.ttf", "Liberation Sans": "LiberationSans-Regular.ttf", Carlito: "Carlito-Regular.ttf" };
// ASCII + diakritika středoevropských jazyků a běžná typografie.
const CHARS = [...new Set([..." !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`abcdefghijklmnopqrstuvwxyz{|}~", ..."áčďéěíňóřšťúůýžÁČĎÉĚÍŇÓŘŠŤÚŮÝŽäöüßÄÖÜąćęłńśźżĄĆĘŁŃŚŹŻĺľŕôÄĹĽŔÔ", ..."–—„“”‚‘’…€§°×"])].join("");

function widths(file) {
  const b = readFileSync(file), u16 = (o) => b.readUInt16BE(o), i16 = (o) => b.readInt16BE(o), u32 = (o) => b.readUInt32BE(o);
  const tables = {};
  for (let i = 0, n = u16(4); i < n; i++) tables[b.toString("latin1", 12 + i * 16, 16 + i * 16)] = u32(20 + i * 16);
  const upem = u16(tables.head + 18), nh = u16(tables.hhea + 34);
  const cmap = tables.cmap;
  let sub = -1;
  for (let i = 0, n = u16(cmap + 2); i < n; i++) {
    const pid = u16(cmap + 4 + i * 8), eid = u16(cmap + 6 + i * 8), off = cmap + u32(cmap + 8 + i * 8);
    if (pid === 3 && eid === 1 && u16(off) === 4) sub = off;
  }
  if (sub < 0) throw new Error(`${file}: no cmap 3/1 format 4`);
  const segs = u16(sub + 6) / 2, ends = sub + 14, starts = ends + segs * 2 + 2, deltas = starts + segs * 2, ranges = deltas + segs * 2;
  const glyphOf = (c) => {
    for (let s = 0; s < segs; s++) {
      if (c > u16(ends + s * 2)) continue;
      const start = u16(starts + s * 2);
      if (c < start) return 0;
      const ro = u16(ranges + s * 2);
      if (!ro) return (c + i16(deltas + s * 2)) & 0xffff;
      const g = u16(ranges + s * 2 + ro + (c - start) * 2);
      return g ? (g + i16(deltas + s * 2)) & 0xffff : 0;
    }
    return 0;
  };
  const adv = (g) => u16(tables.hmtx + Math.min(g, nh - 1) * 4);
  return [...CHARS].map((ch) => Math.round((adv(glyphOf(ch.codePointAt(0))) * 1000) / upem));
}

const lines = Object.entries(FACES).map(([family, f]) => `  ${JSON.stringify(family)}: [${widths(path.join(dir, f)).join(",")}],`);
writeFileSync(path.join(root, "src/lib/converter/pdf/ocr-widths.ts"), `// Generated by scripts/converter/gen-ocr-widths.mjs — do not edit.
// Advance widths (1/1000 em) of CHARS in the regular faces of the bundled metric-compatible fonts.
export const CHARS = ${JSON.stringify(CHARS)};
export const WIDTHS: Record<string, number[]> = {
${lines.join("\n")}
};
`);
